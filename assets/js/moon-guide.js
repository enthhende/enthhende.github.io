  $('#areaAnimalList').innerHTML=animals.length?animals.map(x=>{const id='animal:'+x.no,catchable=x.kind==='소울캐치';return `<article class="areaDetailItem ${isDone(id)?'done':''}" data-progress-row="${esc(id)}" data-area-detail-key="animal:${esc(x.no)}"><div class="areaDetailItemHead"><div>${catchable?progressCheckbox(id,x.name+' 소울캐치 완료'):'—'}</div><div><div class="areaDetailItemTitle">${esc(x.name)}</div><div class="areaDetailMeta">${esc(x.place)} · ${esc(x.time||'시간 조건 없음')}${x.love!==''?` · LOVE +${esc(x.love)}`:''}${x.reward?` · ${esc(x.reward)}`:''}</div></div><span class="badge">${catchable?'애니멀':'이벤트성'}</span></div>${spoiler('area-animal-'+x.no,x.hint,catchable?'캐치 힌트 보기':'이벤트 힌트 보기')}<div class="areaDetailActions"><button class="btn areaJumpBtn" type="button" data-jump-animal="${esc(x.no)}">전체 애니멀 표에서 보기</button></div></article>`}).join(''):'<div class="areaEmpty">이 지역에 등록된 애니멀이 없습니다.</div>';
  const panel=$('#areaDetailPanel');panel.hidden=false;bindProgress(panel);initSpoilers(panel);
