function renderAreas(){
  const map=new Map();
  const ensure=p=>{if(!map.has(p))map.set(p,{love:[],animals:[]});return map.get(p);};
  D.love.forEach(x=>{const p=getPlaceRoot(x.place);if(p)ensure(p).love.push(x);});
  D.animals.forEach(x=>{const p=getPlaceRoot(x.place);if(p)ensure(p).animals.push(x);});
  Object.keys(AREA_CORE_HINTS).forEach(p=>ensure(p));
  const rows=[...map].sort((a,b)=>(b[1].love.length+b[1].animals.length+(AREA_CORE_HINTS[b[0]]?.length||0))-(a[1].love.length+a[1].animals.length+(AREA_CORE_HINTS[a[0]]?.length||0)));
  $('#areaGrid').innerHTML=rows.map(([p,v])=>{
    const loveLinks=v.love.slice(0,4).map(x=>`<button class="areaEventLink" type="button" data-area="${esc(p)}" data-kind="love" data-key="${esc(x.id)}">${esc(x.name)}</button>`).join('');
    const animalLinks=v.animals.slice(0,3).map(x=>`<button class="areaEventLink" type="button" data-area="${esc(p)}" data-kind="animal" data-key="${esc(x.no)}">${esc(x.name)}</button>`).join('');
    const coreCount=AREA_CORE_HINTS[p]?.length||0;
    const coreLink=coreCount?`<button class="areaEventLink" type="button" data-area="${esc(p)}" data-kind="guide" data-key="0">핵심 진행 힌트</button>`:'';
    const extra=Math.max(0,v.love.length+v.animals.length-7);
    return `<article class="areaCard"><h3><button class="areaTitleBtn areaOpen" type="button" data-area="${esc(p)}">${esc(p)}</button></h3><div class="areaStats"><span class="badge">러브 ${v.love.length}</span><span class="badge">애니멀 ${v.animals.length}</span>${coreCount?`<span class="badge important">핵심 진행 ${coreCount}</span>`:''}</div><div class="areaEventLinks">${coreLink}${loveLinks}${animalLinks}${extra?`<span class="badge">+${extra}개</span>`:''}</div><button class="btn areaOpenBtn areaOpen" type="button" data-area="${esc(p)}">지역 상세 보기</button></article>`;
  }).join('');
  $$('.areaOpen',$('#areaGrid')).forEach(btn=>btn.addEventListener('click',()=>openAreaDetail(btn.dataset.area)));
  $$('.areaEventLink',$('#areaGrid')).forEach(btn=>btn.addEventListener('click',()=>openAreaDetail(btn.dataset.area,btn.dataset.kind,btn.dataset.key)));
}
